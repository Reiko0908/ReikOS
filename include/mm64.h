#ifndef MM64_H
#define MM64_H

#include "mm.h"
#define MM64_BITS_PER_LONG 64

#define PAGING64_CPU_BUS_WIDTH 57 /* 57 bit bus - MAX SPACE 4MB */
#define PAGING64_PAGESZ  4096      /* 4KB or 12-bits PAGE NUMBER */

#define GENMASK64(h, l) \
	(((~0ULL) << (l)) & (~0ULL >> (MM64_BITS_PER_LONG  - (h) - 1)))

#define PAGING64_MAX_PGN  (DIV_ROUND_UP(BIT_ULL(21),PAGING64_PAGESZ))
#define PAGING64_PAGE_ALIGNSZ(sz) (DIV_ROUND_UP(sz,PAGING64_PAGESZ)*PAGING64_PAGESZ)

/* Canonical LA57 high-byte tag (bits 63..56) */
#define PAGING64_CANONICAL_TAG_MASK GENMASK64(63, 56)
#define PAGING64_CANONICAL_TAG(x) (((x) & PAGING64_CANONICAL_TAG_MASK) >> 56)

/*
 * LA57 virtual memory layout
 * User              : 0x0000000000000000 - 0x00FFFFFFFFFFFFFF (64 PB)
 * Canonical hole    : 0x0100000000000000 - 0xFEFFFFFFFFFFFFFF (~112 PB)
 * Kernel dynamic map: 0xFF00000000000000 - 0xFFFFFFFF7FFFFFFF (~64 PB)
 * Kernel static text: 0xFFFFFFFF80000000 - 0xFFFFFFFFFFFFFFFF (2 GB)
 */
#define USER_SPACE_START          0x0000000000000000ULL
#define USER_SPACE_END            0x00FFFFFFFFFFFFFFULL

#define USER_STATIC_START         0x0000000000000000ULL
#define USER_STATIC_END           0x00000000000FFFFFULL
#define USER_DYNAMIC_START		  0x0000000000100000ULL
#define USER_DYNAMIC_END          0x00FFFFFFFFFFFFFFULL
#define CANONICAL_HOLE_START      0x0100000000000000ULL
#define CANONICAL_HOLE_END        0xFEFFFFFFFFFFFFFFULL
#define KERNEL_DYNAMIC_START      0xFF00000000000000ULL
#define KERNEL_DYNAMIC_END        0xFFFFFFFF7FFFFFFFULL
#define KERNEL_STATIC_START       0xFFFFFFFF80000000ULL
#define KERNEL_STATIC_END         0xFFFFFFFFFFFFFFFFULL

/* Backward-compatible alias used by existing call sites */
#define KRNL_SPACE_BASE_ADDR KERNEL_DYNAMIC_START

#define IS_USER_SPACE(x)          ((x) >= USER_SPACE_START && (x) <= USER_SPACE_END)
#define IS_CANONICAL_HOLE(x)      ((x) >= CANONICAL_HOLE_START && (x) <= CANONICAL_HOLE_END)
#define IS_KERNEL_DYNAMIC_SPACE(x) ((x) >= KERNEL_DYNAMIC_START && (x) <= KERNEL_DYNAMIC_END)
#define IS_KERNEL_STATIC_SPACE(x) ((x) >= KERNEL_STATIC_START && (x) <= KERNEL_STATIC_END)
#define IS_KRNL_SPACE(x)          (IS_KERNEL_DYNAMIC_SPACE(x) || IS_KERNEL_STATIC_SPACE(x))

static inline int mm64_kernel_dynamic_range_fits(addr_t mapstart, int incpgnum)
{
	if (incpgnum <= 0)
		return 0;

	addr_t mapsz = (addr_t)incpgnum * PAGING64_PAGESZ;
	if (mapsz / PAGING64_PAGESZ != (addr_t)incpgnum)
		return 0; /* multiplication overflow */

	if (mapstart < KERNEL_DYNAMIC_START || mapstart > KERNEL_DYNAMIC_END)
		return 0;

	if (mapstart > KERNEL_DYNAMIC_END - (mapsz - 1))
		return 0; /* crosses into static kernel region */

	return 1;
}

static inline int mm64_user_range_fits(addr_t mapstart, int incpgnum)
{
	if (incpgnum <= 0)
		return 0;

	addr_t mapsz = (addr_t)incpgnum * PAGING64_PAGESZ;
	if (mapsz / PAGING64_PAGESZ != (addr_t)incpgnum)
		return 0; /* multiplication overflow */

	/* must be fully inside USER_SPACE and not cross into canonical hole */
	if (mapstart < USER_SPACE_START || mapstart > USER_SPACE_END)
		return 0;

	if (mapstart > USER_SPACE_END - (mapsz - 1))
		return 0; /* crosses into canonical hole */

	return 1;
}

/* OFFSET */
#define PAGING64_ADDR_OFFST_HIBIT 11
#define PAGING64_ADDR_OFFST_LOBIT 0

/* PT */
#define PAGING64_ADDR_PT_HIBIT 20
#define PAGING64_ADDR_PT_LOBIT 12
#define PAGING64_ADDR_PT_SHIFT 12

/* PMD */
#define PAGING64_ADDR_PMD_HIBIT 29
#define PAGING64_ADDR_PMD_LOBIT 21

/* PUD */
#define PAGING64_ADDR_PUD_HIBIT 38
#define PAGING64_ADDR_PUD_LOBIT 30

/* P4D */
#define PAGING64_ADDR_P4D_HIBIT 47
#define PAGING64_ADDR_P4D_LOBIT 39

/* PGD */
#define PAGING64_ADDR_PGD_HIBIT 56
#define PAGING64_ADDR_PGD_LOBIT 48

#define PAGING64_ADDR_FPN_SHIFT 12
#define PAGING64_ADDR_FPN_LOBIT NBITS(PAGING64_PAGESZ)
#define PAGING64_ADDR_FPN_HIBIT (NBITS(PAGING_MEMRAMSZ) - 1)

/* Extract PGD Entry */
#define PAGING64_ADDR_OFFST(addr) GETVAL(addr,PAGING_ADDR_OFFST_MASK,PAGING_ADDR_OFFST_LOBIT)
#define PAGING64_ADDR_PT(addr) GETVAL(addr,PAGING64_ADDR_PT_MASK,PAGING64_ADDR_PT_LOBIT)
#define PAGING64_ADDR_PMD(addr) GETVAL(addr,PAGING64_ADDR_PMD_MASK,PAGING64_ADDR_PMD_LOBIT)
#define PAGING64_ADDR_PUD(addr) GETVAL(addr,PAGING64_ADDR_PUD_MASK,PAGING64_ADDR_PUD_LOBIT)
#define PAGING64_ADDR_P4D(addr) GETVAL(addr,PAGING64_ADDR_P4D_MASK,PAGING64_ADDR_P4D_LOBIT)
#define PAGING64_ADDR_PGD(addr) GETVAL(addr,PAGING64_ADDR_PGD_MASK,PAGING64_ADDR_PGD_LOBIT)

/* Masks */
#define PAGING64_ADDR_OFFST_MASK  GENMASK64(PAGING_ADDR_OFFST_HIBIT,PAGING_ADDR_OFFST_LOBIT)
#define PAGING64_ADDR_PT_MASK  GENMASK64(PAGING64_ADDR_PT_HIBIT,PAGING64_ADDR_PT_LOBIT)
#define PAGING64_ADDR_PMD_MASK  GENMASK64(PAGING64_ADDR_PMD_HIBIT,PAGING64_ADDR_PMD_LOBIT)
#define PAGING64_ADDR_PUD_MASK  GENMASK64(PAGING64_ADDR_PUD_HIBIT,PAGING64_ADDR_PUD_LOBIT)
#define PAGING64_ADDR_P4D_MASK  GENMASK64(PAGING64_ADDR_P4D_HIBIT,PAGING64_ADDR_P4D_LOBIT)
#define PAGING64_ADDR_PGD_MASK  GENMASK64(PAGING64_ADDR_PGD_HIBIT,PAGING64_ADDR_PGD_LOBIT)
#define PAGING64_OFFST_MASK       GENMASK64(PAGING64_ADDR_OFFST_HIBIT,PAGING64_ADDR_OFFST_LOBIT)
#define PAGING64_PGN_MASK         GENMASK64(PAGING64_ADDR_PGD_HIBIT,PAGING64_ADDR_PT_LOBIT)
#define PAGING64_ADDR_FPN_MASK    GENMASK64(PAGING64_ADDR_FPN_HIBIT,PAGING64_ADDR_FPN_LOBIT)

#define PAGING64_OFFST(x)  GETVAL(x,PAGING64_OFFST_MASK,PAGING64_ADDR_OFFST_LOBIT)
#define PAGING64_PGN(x)  GETVAL(x,PAGING64_PGN_MASK,PAGING64_ADDR_PT_LOBIT)
#define PAGING64_FPN(x)  GETVAL(x,PAGING64_ADDR_FPN_MASK,PAGING64_ADDR_FPN_LOBIT)
#endif
